/**
 * The key a name is looked up under: accents removed, curly apostrophes straightened,
 * underscores read as spaces (Constitute ids), runs of whitespace collapsed, trimmed, lower case.
 * This is the only normalisation; nothing fuzzier.
 */
export const normaliseName = (name) =>
  String(name ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[‘’]/g, "'")
    .replace(/_/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
