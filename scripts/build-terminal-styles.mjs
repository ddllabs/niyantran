#!/usr/bin/env node
// F145 (docs/specs/2026-10-14-globe-handover-and-page-speed.md): the terminal, admin and persona
// chooser load on demand, so a signed-out visitor does not download them. Their stylesheets must not
// move with them: a lazily loaded stylesheet lands after index.css and would change which rule wins.
// This script lists every stylesheet those three reach through static imports, in the order the
// bundler meets them, into src/shell/terminalStyles.js, which App.jsx imports where TerminalShell was.
// The entry keeps the same CSS, in the same order; only the JavaScript moves.
//
//   node scripts/build-terminal-styles.mjs
//
// src/shell/terminalStyles.test.js regenerates the list and fails when the file is out of date.
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = 'src/shell/terminalStyles.js';
// What App.jsx imports before the terminal (already in the entry), then the modules it loads lazily.
export const EAGER_BEFORE = ['src/marketing/MarketingSite.jsx', 'src/marketing/legalRoutes.js'];
export const LAZY_ROOTS = ['src/shell/TerminalShell.jsx', 'src/admin/AdminApp.jsx', 'src/shell/PersonaChooser.jsx'];

const IMPORT = /^\s*(?:import|export)\s+(?:[\w$*{}\s,]+?\s+from\s+)?['"]([^'"\n]+)['"]/gm;

/** The static import specifiers of a module, in source order (dynamic import() is not one). */
export function staticImports(code) {
  return [...code.matchAll(IMPORT)].map(m => m[1]);
}

function resolveFile(spec, from) {
  const base = resolve(dirname(from), spec);
  for (const candidate of [base, `${base}.js`, `${base}.jsx`, join(base, 'index.js'), join(base, 'index.jsx')]) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}

/**
 * Walks static imports from `roots` depth first, as the bundler orders modules, and returns the
 * stylesheets met (repo-relative, or the package path), skipping any `seen` already holds.
 * `modules` collects every source module visited.
 */
export function walk(roots, { seen = new Set(), modules = new Set(), base = root } = {}) {
  const styles = [];
  const visit = (file) => {
    if (modules.has(file)) return;
    modules.add(file);
    for (const spec of staticImports(readFileSync(file, 'utf8'))) {
      if (spec.includes('?')) continue;
      const relativeSpec = spec.startsWith('.');
      if (spec.endsWith('.css')) {
        const key = relativeSpec ? relative(base, resolve(dirname(file), spec)) : spec;
        if (!seen.has(key)) { seen.add(key); styles.push(key); }
        continue;
      }
      if (!relativeSpec) continue;
      const target = resolveFile(spec, file);
      if (target && /\.(jsx?|mjs)$/.test(target)) visit(target);
    }
  };
  roots.forEach(r => visit(join(base, r)));
  return styles;
}

/** The stylesheets the lazy modules bring that the entry does not already have, in order. */
export function terminalStyles(base = root) {
  const seen = new Set();
  const modules = new Set();
  walk(EAGER_BEFORE, { seen, modules, base });
  return walk(LAZY_ROOTS, { seen, modules, base });
}

export function render(styles) {
  const from = dirname(OUTPUT);
  const lines = styles.map(s => `import '${s.startsWith('src/') ? (relative(from, s).startsWith('.') ? relative(from, s) : `./${relative(from, s)}`) : s}';`);
  return `// Generated by scripts/build-terminal-styles.mjs (F145); do not edit by hand.
// The stylesheets of the terminal, admin and persona chooser, which load on demand: kept in the entry,
// in the bundler's order, so the cascade is unchanged.
${lines.join('\n')}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const styles = terminalStyles();
  writeFileSync(join(root, OUTPUT), render(styles));
  console.log(`${OUTPUT}: ${styles.length} stylesheets`);
}
